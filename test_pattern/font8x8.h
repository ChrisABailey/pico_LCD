// Map an ASCII character to its 8-byte glyph row data.  Upper-cases letters and
// returns the blank space glyph for anything not in the table.
static inline const uint8_t *font_glyph(char c) {
    if (c >= 'a' && c <= 'z') c = (char)(c - 'a' + 'A');
    if (c >= 'A' && c <= 'Z') return font8x8[1  + (c - 'A')];
    if (c >= '0' && c <= '9') return font8x8[27 + (c - '0')];
    switch (c) {
        case '.': return font8x8[37];
        case ',': return font8x8[38];
        case ':': return font8x8[39];
        case '-': return font8x8[40];
        case '+': return font8x8[41];
        case '/': return font8x8[42];
        case '*': return font8x8[43];
        case '(': return font8x8[44];
        case ')': return font8x8[45];
        default:  return font8x8[0];   // space / unsupported
    }
}

