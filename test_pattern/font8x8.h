// 8x8 monochrome bitmap font for drawText().
//
// Glyph data is the public-domain font8x8_basic font by Daniel Hepper
// (https://github.com/dhepper/font8x8), trimmed to the characters this
// project needs: space, A-Z, 0-9 and the punctuation . , : - + / * ( ).
//
// Storage convention (matches font8x8_basic):
//   - 8 bytes per glyph, one byte per pixel row, top row first.
//   - Within a row byte, bit 0 (0x01) is the LEFTMOST pixel, bit 7 the rightmost.
// So draw_text() tests `glyph[row] & (1u << col)` with col running 0..7 left->right.
//
// Lower-case letters are upper-cased by font_glyph(); any unsupported character
// maps to the blank space glyph (index 0).

